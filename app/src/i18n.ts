export const dictionaries: Record<Lang, Record<Key, string>> = { pt, en };

let current: Lang = "pt";

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
}

export function getLang(): Lang {
  return current;
}

/** Traduz e troca `{nome}` pelos valores. / Translates and replaces `{name}` with values. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return format(dictionaries[current][key], vars);
}

export function format(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Chave existe? (para códigos de erro vindos do Rust). / Does the key exist? (for Rust error codes). */
export function hasKey(key: string): key is Key {
  return key in pt;
}
